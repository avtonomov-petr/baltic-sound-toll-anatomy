def safe_zscore(M_arr):
    mean_v = np.mean(M_arr, axis=0)
    std_v = np.std(M_arr, axis=0, ddof=1)
    safe_std = np.where(std_v > 1e-12, std_v, 1.0)
    Z = (M_arr - mean_v) / safe_std
    Z[:, std_v <= 1e-12] = 0.0
    return Z

def compute_first_echelon(dlnX, n_boot=300, sample_frac=0.8, seed=42):
    Z = safe_zscore(dlnX)
    M, N = Z.shape
    U, s, Vt = np.linalg.svd(Z, full_matrices=False)
    u1 = np.take(U, 0, axis=1)
    v1 = np.take(Vt, 0, axis=0)
    u2 = np.take(U, 1, axis=1)
    v2 = np.take(Vt, 1, axis=0)
    var1 = (s.item(0)**2) / np.sum(s**2) * 100.0
    var2 = (s.item(1)**2) / np.sum(s**2) * 100.0
    pr_u1 = (1.0 / np.sum(u1**4) - 1.0) / (M - 1.0)
    pr_v1 = (1.0 / np.sum(v1**4) - 1.0) / (N - 1.0)

    rng = np.random.default_rng(seed)
    sub_M = int(np.floor(M * sample_frac))
    boot_pru, boot_prv = [], []
    for _ in range(n_boot):
        idx = np.sort(rng.choice(M, size=sub_M, replace=False))
        Zb = safe_zscore(dlnX[idx, :])
        Ub, _, Vtb = np.linalg.svd(Zb, full_matrices=False)
        u1b = np.take(Ub, 0, axis=1)
        v1b = np.take(Vtb, 0, axis=0)
        boot_pru.append((1.0 / np.sum(u1b**4) - 1.0) / (sub_M - 1.0))
        boot_prv.append((1.0 / np.sum(v1b**4) - 1.0) / (N - 1.0))

    return {
        'var1': var1, 'var2': var2,
        'pr_u1': pr_u1, 'pru_ci': np.percentile(boot_pru, [2.5, 97.5]),
        'pr_v1': pr_v1, 'prv_ci': np.percentile(boot_prv, [2.5, 97.5]),
        'u1': u1, 'v1': v1, 'u2': u2, 'v2': v2
    }

def compute_second_echelon(dlnX, k_nn=8, min_seg=15):
    Z = safe_zscore(dlnX)
    M, N = Z.shape
    dist_mat = squareform(pdist(Z, metric='euclidean'))
    sigma_med = np.median(dist_mat[np.triu_indices(M, k=1)])
    W_full = np.exp(-(dist_mat**2) / (2.0 * sigma_med**2))
    np.fill_diagonal(W_full, 0.0)
    A = np.zeros((M, M))
    for i in range(M):
        nn_idx = np.argsort(dist_mat[i, :])[1:k_nn+1]
        for j in nn_idx:
            A[i, j] = W_full[i, j]
            A[j, i] = W_full[j, i]
    deg = np.sum(A, axis=1)
    d_inv_sqrt = np.diag(1.0 / np.sqrt(np.maximum(deg, 1e-12)))
    L_sym = np.eye(M) - d_inv_sqrt @ A @ d_inv_sqrt
    eigvals, eigvecs = np.linalg.eigh(L_sym)
    psi2 = np.take(eigvecs, 1, axis=1)
    if np.mean(psi2[:M//2]) > np.mean(psi2[M//2:]):
        psi2 = -psi2
    best_p, best_tau = 1.0, -1
    for tau in range(min_seg, M - min_seg):
        _, pval = mannwhitneyu(psi2[:tau], psi2[tau:], alternative='two-sided')
        if pval < best_p:
            best_p, best_tau = pval, tau
    return eigvals[:5], psi2, best_tau, best_p

